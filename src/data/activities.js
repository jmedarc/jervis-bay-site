// HELPER FUNCTIONS FOR FILTERING
// ==========================================

export function filterByType(type) {
  return activities.filter((a) => a.type === type);
}

export function filterByIntensity(intensity) {
  return activities.filter((a) => a.intensity === intensity);
}

export function filterBySurface(surface) {
  return activities.filter((a) => a.surface === surface);
}

export function filterByRainSuitability(mode) {
  return activities.filter((a) => a.rainSuitability && a.rainSuitability.includes(mode));
}

export function filterByDistanceCategory(category) {
  return activities.filter((a) => {
    const km = a.distanceFromHuskissonKm;
    if (km === null) return false;
    switch (category) {
      case "local":
        return km <= 5;
      case "nearby":
        return km > 5 && km <= 15;
      case "day-trip":
        return km > 15 && km <= 50;
      case "regional":
        return km > 50 && km <= 100;
      case "adventure":
        return km > 100;
      default:
        return true;
    }
  });
}

export function filterByTags(tags) {
  return activities.filter((a) => tags.some((tag) => a.tags.includes(tag)));
}

export function getActivityById(id) {
  return activities.find((a) => a.id === id);
}

export default activities;